#!/usr/bin/env bash
#
# build-staging-k93.sh — build the k93 staging bundle for the kDFU boot:
#
#   [stage1 loader][pad to 0x8000][zImage][dtb][pad]
#
# uploaded at 0x80000000 with `irecovery -f staging-bundle.bin` once the iPad
# is in kDFU with the autogo iBEC running (docs/k93-ibec-autogo.md).  The
# autogo hook fires the payload on a SHORT USB completion, so the bundle size
# must NOT be a multiple of 0x8000 — the script pads it off one if needed.
#
# k93 analog of Project Cascadia's scripts/build-staging-bundle.sh, with the
# loader from loader/ (k93 deltas) and our DTS.  The DTB is appended to the
# zImage AND passed in r2 by the loader: the decompressor finds the appended
# DTB by reading the magic at [_edata], which this script verifies is exactly
# the zImage file size before appending (cat zImage dtb puts the DTB there).
#
# Prereqs: scripts/build-kernel-k93.sh (build/out/zImage).  Run inside the
# build container (dtc + arm-linux-gnueabihf-gcc):
#
#   docker run --rm -v "$PWD":/work -w /work cascadia-build \
#       bash scripts/build-staging-k93.sh
#
# Produces:
#   build/out/ipad2-k93ap.dtb      compiled device tree
#   build/out/zImage-dtb           zImage with the DTB appended
#   build/out/linux-boot.bin       stage1 loader (<= 0x8000 bytes)
#   build/out/staging-bundle.bin   the upload image
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CASCADIA="$ROOT/upstream/Project-Cascadia"
TREE="$ROOT/build/linux"
OUT="$ROOT/build/out"

CC=arm-linux-gnueabihf-gcc
OBJCOPY=arm-linux-gnueabihf-objcopy
NM=arm-linux-gnueabihf-nm
READELF=arm-linux-gnueabihf-readelf

TEXT_OFF=32768   # 0x8000: loader budget; zImage starts at 0x80008000
KERNEL_ENTRY=0x80008000

ZIMAGE="$OUT/zImage"
DTS="$ROOT/dts/ipad2-k93ap.dts"
DTB="$OUT/ipad2-k93ap.dtb"
ZDTB="$OUT/zImage-dtb"
LOADER_ELF="$OUT/linux-boot.elf"
LOADER_BIN="$OUT/linux-boot.bin"
BUNDLE="$OUT/staging-bundle.bin"

fail() { echo "error: $*" >&2; exit 1; }

[ -f "$ZIMAGE" ] || fail "missing $ZIMAGE — run: bash scripts/build-kernel-k93.sh"
[ -f "$DTS" ] || fail "missing $DTS"
[ -f "$TREE/arch/arm/boot/compressed/vmlinux" ] || fail "missing $TREE/arch/arm/boot/compressed/vmlinux (kernel tree incomplete?)"
mkdir -p "$OUT"

echo "==> Compiling device tree"
dtc -I dts -O dtb -o "$DTB" "$DTS"
echo "    $(stat -c%s "$DTB") bytes -> $DTB"

echo "==> Appending DTB to zImage"
# The decompressor reads the DTB magic at [_edata]; verify that the zImage
# file size is exactly _edata's file offset, else pad (zeros) up to it.
python3 - "$TREE/arch/arm/boot/compressed/vmlinux" "$ZIMAGE" "$DTB" "$ZDTB" "$KERNEL_ENTRY" <<'PY'
import struct, subprocess, sys
from pathlib import Path

elf, zimg, dtb, zout = (Path(a) for a in sys.argv[1:5])
kentry = int(sys.argv[5], 0)

edata = None
base = None
out = subprocess.run(["arm-linux-gnueabihf-nm", str(elf)], capture_output=True, text=True, check=True).stdout
for line in out.splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[2] == "_edata":
        edata = int(parts[0], 16)
if edata is None:
    raise SystemExit("error: no _edata symbol in " + str(elf))
out = subprocess.run(["arm-linux-gnueabihf-readelf", "-SW", str(elf)], capture_output=True, text=True, check=True).stdout
for line in out.splitlines():
    line = line.strip()
    if not line.startswith("["):
        continue
    f = line.split()
    # [Nr] Name Type Addr Off Size ES Flg ...
    if len(f) >= 6 and f[2] == "PROGBITS":
        addr = int(f[3], 16)
        base = addr if base is None else min(base, addr)
edata_off = edata - base

z = zimg.read_bytes()
if len(z) > edata_off:
    raise SystemExit(f"error: zImage ({len(z):#x}) is larger than _edata's file offset ({edata_off:#x})")
if len(z) < edata_off:
    print(f"    note: padding zImage {len(z):#x} -> {edata_off:#x} to reach _edata")
    z = z + b"\0" * (edata_off - len(z))

d = dtb.read_bytes()
if d[:4] != bytes.fromhex("d00dfeed"):
    raise SystemExit("error: DTB has no d00dfeed magic")
dtb_size = struct.unpack_from(">I", d, 4)[0]
dtb_phys = kentry + len(z)

zout.write_bytes(z + d)
print(f"    zImage      {len(z):#x} bytes @ {kentry:#x}")
print(f"    dtb         {dtb_size:#x} bytes @ {dtb_phys:#x} (file off {len(z):#x})")
print(f"    _edata check: file size {len(z):#x} == _edata file offset {edata_off:#x} OK")

inc = zout.parent / "staging-generated.h"
inc.write_text(
    "/* Auto-generated by build-staging-k93.sh — do not edit */\n"
    "#ifndef STAGING_GENERATED_H\n#define STAGING_GENERATED_H\n"
    f"#define DTB_PHYS {dtb_phys:#x}u\n"
    f"#define DTB_SIZE {dtb_size:#x}u\n"
    "#endif\n"
)
print(f"    staging-generated.h: DTB_PHYS {dtb_phys:#x} DTB_SIZE {dtb_size:#x}")
PY

echo "==> Building stage1 loader"
# fb_text8.h / font8x8.h come from the Cascadia pongo/ dir; staging-generated.h
# from build/out.  --build-id=none: a .note.gnu.build-id would shift .text and
# corrupt the entry (this container's binutils 2.38 also rejects
# --no-warn-rwx-segments, so that flag is deliberately absent).
"$CC" -static -nostdlib -nostartfiles -O2 \
    -I "$CASCADIA/pongo" -I "$OUT" \
    -fno-builtin -ffreestanding \
    -Wl,--build-id=none \
    -Wl,-T,"$ROOT/loader/linux-boot.ld" \
    -o "$LOADER_ELF" \
    "$ROOT/loader/linux_boot_start.S" \
    "$ROOT/loader/linux_boot.c"
"$OBJCOPY" -O binary "$LOADER_ELF" "$LOADER_BIN"

# Guard against the section-shift class of bug: the entry symbol must land on
# its exact VA, or every PC-relative encoding in the loader is off.
entry=$("$NM" "$LOADER_ELF" | awk '$3 == "_start" { print $1 }')
[ "$entry" = "80000000" ] || fail "loader _start is at 0x$entry, expected 0x80000000 (linker script / build-id problem?)"

lsz=$(stat -c%s "$LOADER_BIN")
if [ "$lsz" -gt "$TEXT_OFF" ]; then
    fail "linux-boot.bin is ${lsz} bytes (max ${TEXT_OFF})"
fi
echo "    loader ${lsz} bytes, _start @ 0x80000000 verified"

echo "==> Assembling staging bundle"
cp "$LOADER_BIN" "$BUNDLE"
pad=$((TEXT_OFF - lsz))
if [ "$pad" -gt 0 ]; then
    dd if=/dev/zero bs=1 count="$pad" status=none >> "$BUNDLE"
fi
cat "$ZDTB" >> "$BUNDLE"

# The autogo hook fires on a SHORT final USB transfer: the bundle must not be
# a multiple of 0x8000.  Trailing bytes after the DTB are harmless — the
# decompressor reads magic+size at [_edata] and the kernel parses the DTB by
# its own totalsize.
bsz=$(stat -c%s "$BUNDLE")
if [ $((bsz % 0x8000)) -eq 0 ]; then
    dd if=/dev/zero bs=1 count=4 status=none >> "$BUNDLE"
    echo "    padded +4 so the final transfer is short (autogo EOF)"
    bsz=$(stat -c%s "$BUNDLE")
fi
if [ $((bsz % 0x8000)) -eq 0 ]; then
    fail "bundle is still a multiple of 0x8000"
fi

echo "==> Done"
echo "  loader : ${lsz} bytes + ${pad} pad"
echo "  kernel : $(stat -c%s "$ZDTB") bytes (zImage-dtb)"
echo "  bundle : ${bsz} bytes (${bsz} % 0x8000 = $((bsz % 0x8000)))"
echo "  upload : irecovery -f build/out/staging-bundle.bin   (0x80000000)"
echo "  chain  : kDFU -> pwned iBSS -> autogo iBEC -> loader -> 0x80008000"
